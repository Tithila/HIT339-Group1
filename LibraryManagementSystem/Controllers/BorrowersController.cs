using LibraryManagementSystem.Data;
using LibraryManagementSystem.Models;
using LibraryManagementSystem.Services;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;

namespace LibraryManagementSystem.Controllers;

[Authorize(Roles = "Reception,Admin")]
public class BorrowersController : Controller
{
    private readonly ApplicationDbContext _context;
    private readonly IBorrowerEligibilityService _borrowerEligibilityService;
    private readonly INotificationService _notificationService;

    public BorrowersController(
        ApplicationDbContext context,
        IBorrowerEligibilityService borrowerEligibilityService,
        INotificationService notificationService)
    {
        _context = context;
        _borrowerEligibilityService = borrowerEligibilityService;
        _notificationService = notificationService;
    }

    // =========================================================
    // BORROWER LIST
    // =========================================================

    // GET: Borrowers
    public async Task<IActionResult> Index()
    {
        // Recalculate borrower eligibility so old/stale
        // suspension records are corrected automatically.
        var borrowerIds = await _context.Borrowers
            .AsNoTracking()
            .Select(b => b.Id)
            .ToListAsync();

        foreach (var borrowerId in borrowerIds)
        {
            await _borrowerEligibilityService
                .CheckAndUpdateSuspensionAsync(borrowerId);
        }

        var borrowers = await _context.Borrowers
            .AsNoTracking()
            .OrderBy(b => b.FullName)
            .ToListAsync();

        return View(borrowers);
    }

    // =========================================================
    // DETAILS
    // =========================================================

    // GET: Borrowers/Details/5
    public async Task<IActionResult> Details(int? id)
    {
        if (id == null)
        {
            return NotFound();
        }

        await _borrowerEligibilityService
            .CheckAndUpdateSuspensionAsync(id.Value);

        var borrower = await _context.Borrowers
            .AsNoTracking()
            .FirstOrDefaultAsync(b => b.Id == id.Value);

        if (borrower == null)
        {
            return NotFound();
        }

        var activeLoans = await _context.Loans
            .AsNoTracking()
            .Include(l => l.Item)
            .Where(l =>
                l.BorrowerId == borrower.Id &&
                l.ReturnDate == null)
            .OrderBy(l => l.DueDate)
            .ToListAsync();

        var outstandingFine = await _context.Loans
            .AsNoTracking()
            .Where(l =>
                l.BorrowerId == borrower.Id &&
                l.FineAmount > 0 &&
                !l.FinePaid)
            .SumAsync(l => l.FineAmount);

        ViewBag.ActiveLoans = activeLoans;
        ViewBag.OutstandingFine = outstandingFine;

        return View(borrower);
    }

    // =========================================================
    // CREATE
    // =========================================================

    // GET: Borrowers/Create
    public IActionResult Create()
    {
        return View(new Borrower());
    }

    // POST: Borrowers/Create
    [HttpPost]
    [ValidateAntiForgeryToken]
    public async Task<IActionResult> Create(
        [Bind("FullName,Email,Phone")] Borrower borrower)
    {
        if (!ModelState.IsValid)
        {
            return View(borrower);
        }

        // Library card numbers are generated by the system.
        borrower.LibraryCardNumber =
            await GenerateUniqueLibraryCardNumberAsync();

        // A new borrower starts active.
        borrower.IsSuspended = false;
        borrower.SuspensionReason = null;

        _context.Borrowers.Add(borrower);

        await _context.SaveChangesAsync();

        await _notificationService.SendAsync(
    borrower.Id,
    borrower.Email,
    NotificationChannel.Email,
    NotificationType.Welcome,
    $"Welcome to the Library, {borrower.FullName}! " +
    $"Your membership has been created successfully. " +
    $"Your library card number is {borrower.LibraryCardNumber}. " +
    $"Please keep this number safe. You can use it at the self-service kiosk.");

        TempData["SuccessMessage"] =
            $"{borrower.FullName} was registered successfully. " +
            $"Library card: {borrower.LibraryCardNumber}";

        return RedirectToAction(
            nameof(Details),
            new { id = borrower.Id });
    }

    // =========================================================
    // EDIT
    // =========================================================

    // GET: Borrowers/Edit/5
    public async Task<IActionResult> Edit(int? id)
    {
        if (id == null)
        {
            return NotFound();
        }

        var borrower = await _context.Borrowers
            .FindAsync(id.Value);

        if (borrower == null)
        {
            return NotFound();
        }

        return View(borrower);
    }

    // POST: Borrowers/Edit/5
    [HttpPost]
    [ValidateAntiForgeryToken]
    public async Task<IActionResult> Edit(
        int id,
        [Bind("Id,FullName,Email,Phone")] Borrower model)
    {
        if (id != model.Id)
        {
            return NotFound();
        }

        if (!ModelState.IsValid)
        {
            return View(model);
        }

        var borrower = await _context.Borrowers
            .FirstOrDefaultAsync(b => b.Id == id);

        if (borrower == null)
        {
            return NotFound();
        }

        // Only allow Reception/Admin to edit contact details.
        // Library card and suspension information are controlled
        // by the system.
        borrower.FullName = model.FullName;
        borrower.Email = model.Email;
        borrower.Phone = model.Phone;

        try
        {
            await _context.SaveChangesAsync();

            await _borrowerEligibilityService
                .CheckAndUpdateSuspensionAsync(borrower.Id);
        }
        catch (DbUpdateConcurrencyException)
        {
            if (!BorrowerExists(borrower.Id))
            {
                return NotFound();
            }

            throw;
        }

        TempData["SuccessMessage"] =
            $"{borrower.FullName}'s details were updated.";

        return RedirectToAction(
            nameof(Details),
            new { id = borrower.Id });
    }

    // =========================================================
    // DELETE
    // =========================================================

    // Deleting borrower records is restricted to Admin.
    [Authorize(Roles = "Admin")]
    public async Task<IActionResult> Delete(int? id)
    {
        if (id == null)
        {
            return NotFound();
        }

        var borrower = await _context.Borrowers
            .AsNoTracking()
            .FirstOrDefaultAsync(b => b.Id == id.Value);

        if (borrower == null)
        {
            return NotFound();
        }

        return View(borrower);
    }

    // POST: Borrowers/Delete/5
    [HttpPost]
    [ActionName("Delete")]
    [ValidateAntiForgeryToken]
    [Authorize(Roles = "Admin")]
    public async Task<IActionResult> DeleteConfirmed(int id)
    {
        var borrower = await _context.Borrowers
            .FindAsync(id);

        if (borrower == null)
        {
            return NotFound();
        }

        var hasLoans = await _context.Loans
            .AnyAsync(l => l.BorrowerId == borrower.Id);

        if (hasLoans)
        {
            TempData["ErrorMessage"] =
                "This borrower cannot be deleted because loan history exists.";

            return RedirectToAction(
                nameof(Details),
                new { id = borrower.Id });
        }

        _context.Borrowers.Remove(borrower);

        await _context.SaveChangesAsync();

        TempData["SuccessMessage"] =
            "Borrower deleted successfully.";

        return RedirectToAction(nameof(Index));
    }

    // =========================================================
    // HELPERS
    // =========================================================

    private async Task<string>
        GenerateUniqueLibraryCardNumberAsync()
    {
        string cardNumber;

        do
        {
            cardNumber =
                $"LC-{Guid.NewGuid()
                    .ToString("N")[..8]
                    .ToUpperInvariant()}";
        }
        while (await _context.Borrowers
            .AnyAsync(b =>
                b.LibraryCardNumber == cardNumber));

        return cardNumber;
    }

    private bool BorrowerExists(int id)
    {
        return _context.Borrowers
            .Any(b => b.Id == id);
    }
}